"""Начальное наполнение: каталог предметов для магазина."""
from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import Item, Слот

# Цены из концепции: первая вещь доступна в первый день, транспорт — примерно за месяц.
КАТАЛОГ = [
    ("cap_neon", "Неоновая кепка", "Кепка с символом приглашения командной строки",
     Слот.ГОЛОВА, 40, "cap", 10),
    ("glasses_debug", "Очки отладки", "Подсвеченные линзы — видно каждую ошибку",
     Слот.ЛИЦО, 120, "glasses", 20),
    ("hoodie_python", "Худи Python", "Пиксельный питон на груди",
     Слот.ТЕЛО, 250, "hoodie", 30),
    ("backpack_dev", "Рюкзак разработчика", "Торчащие кабели и запасной аккумулятор",
     Слот.СПИНА, 400, "backpack", 40),
    ("skin_neon", "Неоновые иглы", "Бирюзовые иглы с мягким свечением",
     Слот.СКИН, 650, "skin_neon", 50),
    ("skin_chrome", "Хромированный ёж", "Металлическая текстура тела",
     Слот.СКИН, 1100, "skin_chrome", 60),
    ("vehicle_hogmobile", "Хог-мобиль", "Личный транспорт кибер-ежа",
     Слот.ТРАНСПОРТ, 1800, "hogmobile", 70),
    ("home_capsule", "Капсула кодера", "Комната с рабочим столом на фоне",
     Слот.ДОМ, 4500, "capsule", 80),
    ("home_loft", "Кибер-лофт", "Панорама города и серверная стойка",
     Слот.ДОМ, 8000, "loft", 90),
]


def засеять_каталог(сессия: Session) -> int:
    """Добавляет недостающие предметы. Повторный вызов ничего не ломает."""
    добавлено = 0
    for sku, имя, описание, слот, цена, ключ, порядок in КАТАЛОГ:
        если_есть = сессия.scalar(select(Item).where(Item.sku == sku))
        if если_есть:
            continue
        сессия.add(Item(
            sku=sku, name=имя, description=описание, slot=слот,
            price=цена, asset_key=ключ, sort_order=порядок,
        ))
        добавлено += 1
    сессия.commit()
    return добавлено
