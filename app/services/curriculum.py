ВСТУПЛЕНИЕ.update({"none": МОДУЛЬ_С_НУЛЯ, "other": МОДУЛЬ_ПЕРЕХОД})


def каркас(уровень: Уровень, опыт: str = "") -> tuple[МодульКурса, ...]:
    """Модули курса. Перед ними — вводный модуль по опыту, если он нужен.

    опыт = "none"   — никогда не программировал: МОДУЛЬ_С_НУЛЯ;
    опыт = "other"  — писал на другом языке: МОДУЛЬ_ПЕРЕХОД;
    иначе вводного модуля нет.
    """
    основа = КАРКАС.get(уровень, КАРКАС[Уровень.НОВИЧОК])
    вводный = ВСТУПЛЕНИЕ.get(опыт)
    return (вводный, *основа) if вводный else основа


def все_модули(уровень: Уровень) -> tuple[МодульКурса, ...]:
    """Все модули, которые могут встретиться в курсе этого уровня, — для поиска темы."""
    return (*ВСТУПЛЕНИЕ.values(), *КАРКАС.get(уровень, КАРКАС[Уровень.НОВИЧОК]))


def всего_уроков(уровень: Уровень) -> int:
    return sum(len(м.уроки) for м in каркас(уровень))
